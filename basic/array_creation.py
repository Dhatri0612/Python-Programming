import numpy as np
# 1D array
arr=np.array([10,20,30,40])
print(arr)

# 2D array
arr1=np.array([[1,2,3,4],[5,6,7,8]])
print(arr1)

# zeros
arr2=np.zeros((3,3))
print(arr2)

# ones
arr3=np.ones((2,4))
print(arr3)

# range
arr4=np.arange(0,21,2)
print(arr4)

# linspace
arr5=np.linspace(1,10,5)
print(arr5)